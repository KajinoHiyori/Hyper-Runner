//=============================
// Goal生成処理
//=============================
CGoal* CGoal::Create(float fLine)
{
	CGoal* pGoal = NULL;	// オブジェクトへのポインタを用意
	if (pGoal == NULL)
	{ // NULLが設定できている場合
		pGoal = new CGoal;
		if (pGoal != NULL)
		{ // インスタンス生成に成功した場合
			// 初期化処理
			pGoal->Init(fLine);

			// 種類設定
			pGoal->SetType(TYPE_GOAL);

			return pGoal;
		}
	}
	// インスタンス生成に失敗
	return NULL;
}

//=============================
// 初期化処理
//=============================
HRESULT CGoal::Init(float fLine)
{
	// 初期化
	m_fLine = fLine;

	return S_OK;
}

